#pragma once

#include <random>

class RandomGenerator {
public:
    /**
     * @brief Создает новый генератор псевдослучайных чисел std::mt19937
     *
     * @return новый генератор с уникальным начальным значением
     */
    static std::mt19937 getGenerator();

    /**
     * @brief Возвращает одно случайное число из отрезка [min, max].
     *
     * @param min нижняя граница (включительно)
     * @param max верхняя граница (включительно)
     * @return случайное целое число: min <= число <= max
     */
    static int getRandom(int min, int max);

    /**
     * @brief Возвращает одно случайное число из отрезка [min, max], используя переданный генератор.
     *
     * Генератор передается по неконстантной ссылке, потому что при каждом вызове
     * его внутреннее состояние меняется (сдвигается к следующему числу).
     *
     * @param gen созданный ранее генератор псевдослучайных чисел
     * @param min нижняя граница (включительно)
     * @param max верхняя граница (включительно)
     * @return случайное целое число: min <= число <= max
     */
    static int getRandom(std::mt19937& gen, int min, int max);

    /**
     * @brief Создает равномерное распределение целых чисел на отрезке [min, max].
     *
     * @param min нижняя граница (включительно)
     * @param max верхняя граница (включительно)
     * @return объект распределения
     */
    static std::uniform_int_distribution<> getDist(int min, int max);
};
